'use strict';

/**
 * Finding report rendering.
 *
 * A finding in VulnDesk is not just a row — it renders as the professional
 * report a triage team would forward to an engineering team or attach to a
 * bounty payout decision: metadata table, description, reproduction steps,
 * impact, remediation, and dedupe provenance.
 */

function renderMarkdown(finding, ctx = {}) {
  const lines = [];
  lines.push(`# ${finding.title}`);
  lines.push('');
  lines.push('| Field | Value |');
  lines.push('| --- | --- |');
  lines.push(`| Severity | ${finding.severityBand.toUpperCase()} (${finding.severityScore.toFixed(1)}) |`);
  lines.push(`| CVSS vector | \`${finding.cvssVector}\` |`);
  lines.push(`| Status | ${finding.status} |`);
  lines.push(`| Class | ${finding.vulnClass} |`);
  lines.push(`| Target | ${finding.target} |`);
  if (finding.parameter) lines.push(`| Parameter | \`${finding.parameter}\` |`);
  if (ctx.programmeName) lines.push(`| Programme | ${ctx.programmeName} |`);
  if (finding.reporter) lines.push(`| Reporter | ${finding.reporter} |`);
  if (ctx.assigneeName) lines.push(`| Assignee | ${ctx.assigneeName} |`);
  lines.push(`| Reported | ${finding.createdAt} |`);
  lines.push(`| Last updated | ${finding.updatedAt} |`);
  lines.push(`| Fingerprint | \`${finding.fingerprint}\` |`);
  if (finding.duplicateOf) lines.push(`| Duplicate of | ${finding.duplicateOf} |`);
  lines.push('');
  lines.push('## Description');
  lines.push('');
  lines.push(finding.description || '_No description provided._');
  lines.push('');
  lines.push('## Steps to Reproduce');
  lines.push('');
  lines.push(finding.reproduction || '_No reproduction steps provided._');
  lines.push('');
  lines.push('## Impact');
  lines.push('');
  lines.push(finding.impact || '_No impact statement provided._');
  lines.push('');
  lines.push('## Remediation');
  lines.push('');
  lines.push(finding.remediation || '_No remediation guidance provided._');
  lines.push('');
  lines.push('---');
  lines.push('_Generated by VulnDesk_');
  lines.push('');
  return lines.join('\n');
}

module.exports = { renderMarkdown };
